<?php

namespace App\Filament\Resources;

use App\Filament\Resources\EodReportResource\Pages;
use App\Models\EodReport;
use App\Models\Store;
use App\Services\EodCloseoutService;
use Filament\Forms;
use Filament\Forms\Form;
use Filament\Notifications\Notification;
use Filament\Resources\Resource;
use Filament\Tables;
use Filament\Tables\Table;

class EodReportResource extends Resource
{
    protected static ?string $model = EodReport::class;

    protected static ?string $navigationIcon = 'heroicon-o-document-chart-bar';

    protected static ?string $navigationGroup = 'POS & Registers';

    protected static ?string $navigationLabel = 'EOD & Z-Reports';

    protected static ?int $navigationSort = 3;

    public static function form(Form $form): Form
    {
        return $form
            ->schema([
                Forms\Components\Section::make('EOD Summary Overview')
                    ->schema([
                        Forms\Components\Select::make('store_id')
                            ->relationship('store', 'name')
                            ->required()
                            ->disabled(),
                        Forms\Components\DatePicker::make('report_date')
                            ->required()
                            ->disabled(),
                        Forms\Components\Toggle::make('is_automated')
                            ->label('Generated by Automated Nightly Scheduler')
                            ->disabled(),
                        Forms\Components\TextInput::make('closed_sessions_count')
                            ->label('Registers Closed')
                            ->disabled(),
                        Forms\Components\TextInput::make('gross_sales')
                            ->prefix('LKR')
                            ->disabled(),
                        Forms\Components\TextInput::make('net_sales')
                            ->prefix('LKR')
                            ->disabled(),
                        Forms\Components\TextInput::make('total_cash_sales')
                            ->prefix('LKR')
                            ->disabled(),
                        Forms\Components\TextInput::make('total_card_sales')
                            ->prefix('LKR')
                            ->disabled(),
                        Forms\Components\TextInput::make('total_gift_card_sales')
                            ->prefix('LKR')
                            ->disabled(),
                        Forms\Components\TextInput::make('total_refunds')
                            ->prefix('LKR')
                            ->disabled(),
                        Forms\Components\TextInput::make('total_opening_float')
                            ->prefix('LKR')
                            ->disabled(),
                        Forms\Components\TextInput::make('expected_cash')
                            ->prefix('LKR')
                            ->disabled(),
                        Forms\Components\TextInput::make('actual_closing_cash')
                            ->prefix('LKR')
                            ->disabled(),
                        Forms\Components\TextInput::make('net_discrepancy')
                            ->prefix('LKR')
                            ->disabled(),
                        Forms\Components\Textarea::make('notes')
                            ->columnSpanFull()
                            ->disabled(),
                    ])->columns(3),
            ]);
    }

    public static function table(Table $table): Table
    {
        return $table
            ->columns([
                Tables\Columns\TextColumn::make('report_date')
                    ->date('Y-m-d')
                    ->sortable()
                    ->weight('bold'),
                Tables\Columns\TextColumn::make('store.name')
                    ->searchable()
                    ->sortable(),
                Tables\Columns\TextColumn::make('gross_sales')
                    ->money('LKR')
                    ->sortable()
                    ->weight('bold'),
                Tables\Columns\TextColumn::make('total_cash_sales')
                    ->label('Cash')
                    ->money('LKR')
                    ->toggleable(),
                Tables\Columns\TextColumn::make('total_card_sales')
                    ->label('Card')
                    ->money('LKR')
                    ->toggleable(),
                Tables\Columns\TextColumn::make('closed_sessions_count')
                    ->label('Registers')
                    ->badge()
                    ->color('info')
                    ->sortable(),
                Tables\Columns\TextColumn::make('net_discrepancy')
                    ->label('Variance')
                    ->money('LKR')
                    ->color(fn ($state) => (float) $state < -0.01 ? 'danger' : ((float) $state > 0.01 ? 'warning' : 'success'))
                    ->weight('bold'),
                Tables\Columns\IconColumn::make('is_automated')
                    ->label('Scheduled')
                    ->boolean()
                    ->trueIcon('heroicon-o-clock')
                    ->falseIcon('heroicon-o-user')
                    ->trueColor('primary')
                    ->falseColor('secondary'),
                Tables\Columns\TextColumn::make('created_at')
                    ->dateTime('M d, H:i')
                    ->sortable()
                    ->toggleable(isToggledHiddenByDefault: true),
            ])
            ->defaultSort('report_date', 'desc')
            ->actions([
                Tables\Actions\ViewAction::make(),
                Tables\Actions\Action::make('resend_sms')
                    ->label('Resend SMS')
                    ->icon('heroicon-o-chat-bubble-bottom-center-text')
                    ->color('warning')
                    ->requiresConfirmation()
                    ->modalHeading('Resend EOD Executive SMS')
                    ->modalDescription('Dispatch a concise EOD financial digest SMS to the store manager.')
                    ->form([
                        Forms\Components\TextInput::make('recipient_phone')
                            ->label('Override Phone (Optional)')
                            ->placeholder('e.g. 0771234567'),
                    ])
                    ->action(function (EodReport $record, array $data, EodCloseoutService $service) {
                        $service->dispatchEodSms($record, $record->store, $data['recipient_phone'] ?? null);
                        Notification::make()
                            ->title('EOD SMS Queued')
                            ->success()
                            ->send();
                    }),
            ])
            ->bulkActions([]);
    }

    public static function getPages(): array
    {
        return [
            'index' => Pages\ListEodReports::route('/'),
        ];
    }
}
